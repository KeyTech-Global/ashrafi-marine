import fs from "node:fs";

const manifest = JSON.parse(fs.readFileSync("public/images/manifest.json", "utf8"));

const map = {
  heroHarbour: ["hero-harbour", "Fishing boats docked in a harbour at dusk"],
  heroBoatSunset: ["hero-boat-sunset", "A fishing boat on the ocean at sunset"],
  productJawla: [
    "product-jawla",
    "Dried tiny prawns (Jawla), also called baby dry shrimp or sookha jheenga",
  ],
  productMixed: [
    "product-mixed",
    "An assortment of dried fish varieties at a coastal market",
  ],
  productOther: ["product-other", "Dried small fish piled on a dark surface"],
  dryingRack: ["drying-rack", "Dried fish hanging on an outdoor drying rack"],
  driedHanging: ["dried-hanging", "Dried fish hanging from a rope in the sun"],
  marketFish: ["market-fish", "Fresh fish displayed at an Indian market"],
  harbourSunny: ["harbour-sunny", "Fishing boats docked in a sunny harbour"],
  oceanAerial: ["ocean-aerial", "Aerial view of ocean waves"],
  driedContainer: ["dried-container", "Dried fish arranged in a white container"],
  fishHeads: ["fish-heads", "Fish drying on a metal rack in the sun"],
};

let out = `// Generated by scripts/prepare-images.mjs — replace the webp files to use your own photography.\n\nexport type ImageAsset = {\n  src: string;\n  alt: string;\n  width: number;\n  height: number;\n  blurDataURL: string;\n};\n\nexport const images = {\n`;

for (const [key, [file, alt]] of Object.entries(map)) {
  const data = manifest[file];
  out += `  ${key}: {\n    src: "/images/${file}.webp",\n    alt: ${JSON.stringify(alt)},\n    width: ${data.width},\n    height: ${data.height},\n    blurDataURL:\n      ${JSON.stringify(data.blurDataURL)},\n  },\n`;
}

out += "} as const;\n\nexport type ImageKey = keyof typeof images;\n";

fs.writeFileSync("src/content/images.ts", out);
console.log("wrote", out.length, "chars");
